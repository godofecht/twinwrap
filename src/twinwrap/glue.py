"""Per-language glue that exports the shared ``twinwrap_*`` C interface.

Flow: a C unit appended to the compiler's output. Each ``twinwrap_<name>``
forwards to the ``flow_export_<name>`` alias that ``--export`` creates, and
the Flow function takes the C parameters in the same order (a slice is a
``ptr<T>`` followed by an ``i32`` length; a returned array is a trailing
``ptr<T>`` and ``i32`` length, and the Flow return value is ignored).

Rust: a separate cdylib crate that depends on the user's crate by path, so
the user's crate never changes. Each export converts the C parameters into
``&[T]`` and ``&str``, calls the user's function, and copies the result
back out. A panic is caught and reported through ``twinwrap_take_error``.
"""

from __future__ import annotations

import re
import tomllib
from pathlib import Path

from .manifest import Manifest
from .sig import SCALARS, Signature, c_params, c_prototype

ABI_VERSION = 1

# ---------------------------------------------------------------- Flow / C

C_PRELUDE = f"""
/* ---- twinwrap glue: generated, do not edit ---- */
#include <stdint.h>
#include <stdbool.h>
#include <stdlib.h>
#if defined(__wasm__)
#define TWINWRAP_EXPORT(n) __attribute__((export_name(#n), used))
#elif defined(_WIN32)
#define TWINWRAP_EXPORT(n) __declspec(dllexport)
#else
#define TWINWRAP_EXPORT(n) __attribute__((visibility("default"), used))
#endif
TWINWRAP_EXPORT(twinwrap_abi_version) int32_t twinwrap_abi_version(void) {{ return {ABI_VERSION}; }}
TWINWRAP_EXPORT(twinwrap_alloc) void *twinwrap_alloc(int32_t n) {{ return malloc(n > 0 ? (size_t)n : 1); }}
TWINWRAP_EXPORT(twinwrap_free) void twinwrap_free(void *p, int32_t n) {{ (void)n; free(p); }}
"""

# The Flow prelude references a few POSIX calls WASI does not have. Library
# code never reaches them; these stubs only let the unit compile.
WASI_COMPAT_H = """\
/* twinwrap: force-included when compiling Flow output for wasm32-wasip1. */
#include <stdio.h>
#include <sys/resource.h>
static inline FILE *popen(const char *c, const char *m) { (void)c; (void)m; return 0; }
static inline int pclose(FILE *f) { (void)f; return -1; }
static inline int system(const char *c) { (void)c; return -1; }
#define ru_maxrss ru_utime.tv_sec
"""


def flow_glue(m: Manifest) -> str:
    out = [C_PRELUDE]
    for sig in m.functions:
        args = ", ".join(name for _, name in c_params(sig))
        call = f"flow_export_{sig.name}({args})"
        body = f"return {call};" if sig.ret.kind == "scalar" else f"(void){call};"
        out.append(f"TWINWRAP_EXPORT({sig.symbol}) {c_prototype(sig)} {{ {body} }}")
    return "\n".join(out) + "\n"


def c_header(m: Manifest) -> str:
    guard = re.sub(r"\W", "_", m.lib_name).upper() + "_TWINWRAP_H"
    lines = [
        f"/* {m.name} {m.version}: C interface generated by twinwrap. */",
        f"#ifndef {guard}",
        f"#define {guard}",
        "#include <stdint.h>",
        "#include <stdbool.h>",
        "#ifdef __cplusplus",
        'extern "C" {',
        "#endif",
        "int32_t twinwrap_abi_version(void);",
        "void *twinwrap_alloc(int32_t n);",
        "void twinwrap_free(void *p, int32_t n);",
    ]
    for sig in m.functions:
        if sig.doc:
            lines.append(f"/* {sig.doc} */")
        lines.append(c_prototype(sig) + ";")
    lines += ["#ifdef __cplusplus", "}", "#endif", f"#endif /* {guard} */", ""]
    return "\n".join(lines)


def flow_expected_signature(sig: Signature) -> str:
    """The Flow declaration that matches the C interface, for docs and errors."""
    parts: list[str] = []
    for p in sig.params:
        t = p.type
        if t.kind == "scalar":
            parts.append(f"{p.name}: {t.elem}")
        elif t.kind == "slice":
            parts.append(f"{p.name}: ptr<{t.elem}>, {p.name}_len: i32")
        elif t.kind == "str":
            parts.append(f"{p.name}: ptr<u8>, {p.name}_len: i32")
    if sig.ret.kind == "array":
        parts.append(f"out: ptr<{sig.ret.elem}>, out_len: i32")
    ret = f" -> {sig.ret.elem}" if sig.ret.kind == "scalar" else " -> i32"
    return f"function {sig.name}({', '.join(parts)}){ret}"


# ------------------------------------------------------------------- Rust

RUST_TYPES = {k: k for k in SCALARS}


def rust_crate_ident(crate_dir: Path) -> str:
    data = tomllib.loads((crate_dir / "Cargo.toml").read_text(encoding="utf-8"))
    lib = data.get("lib") or {}
    name = lib.get("name") or (data.get("package") or {}).get("name")
    if not name:
        raise ValueError(f"{crate_dir}/Cargo.toml has no package name")
    return name.replace("-", "_")


def rust_package_name(crate_dir: Path) -> str:
    return tomllib.loads((crate_dir / "Cargo.toml").read_text(encoding="utf-8"))["package"]["name"]


def rust_cargo_toml(m: Manifest, crate_dir: Path) -> str:
    dep = rust_package_name(crate_dir)
    extra = ""
    if not m.default_features:
        extra += ", default-features = false"
    if m.features:
        extra += ", features = [" + ", ".join(f'"{x}"' for x in m.features) + "]"
    return f"""# Generated by twinwrap. Do not edit; it is rewritten on every build.
[package]
name = "{m.lib_name}_twinwrap"
version = "{m.version}"
edition = "2021"
publish = false

[lib]
name = "{m.lib_name}"
crate-type = ["cdylib"]
path = "lib.rs"

[dependencies]
{dep} = {{ path = "{crate_dir.as_posix()}"{extra} }}

[profile.release]
opt-level = 3
lto = true
codegen-units = 1

[workspace]
"""


def _rust_fn(m: Manifest, crate: str, sig: Signature) -> str:
    target = m.rust_paths.get(sig.name, sig.name)
    path = f"::{crate}::{target}"
    cps = c_params(sig)

    def rty(ctype: str) -> str:
        ctype = ctype.strip()
        mut = "*mut" if not ctype.startswith("const") else "*const"
        base = ctype.replace("const", "").replace("*", "").strip()
        rust = {v[0]: k for k, v in SCALARS.items()}[base]
        if rust == "bool" and "*" not in ctype:
            return "bool"
        return f"{mut} {rust}" if "*" in ctype else rust

    params = ", ".join(f"{n}: {rty(t)}" for t, n in cps)
    pre: list[str] = []
    args: list[str] = []
    for p in sig.params:
        t = p.type
        if t.kind == "scalar":
            args.append(p.name)
        elif t.kind == "slice":
            pre.append(f"let {p.name} = __slice({p.name}_ptr, {p.name}_len);")
            args.append(p.name)
        elif t.kind == "str":
            pre.append(f"let {p.name} = __str({p.name}_ptr, {p.name}_len)?;")
            args.append(p.name)
    call = f"{path}({', '.join(args)})"
    r = sig.ret
    if r.kind == "scalar":
        ret_ty = f" -> {r.elem}"
        body = f"let __r: {r.elem} = {call}; Ok(__r)"
        default = "Default::default()"
    elif r.kind == "none":
        ret_ty = ""
        body = f"{call}; Ok(())"
        default = "()"
    elif r.kind == "array":
        ret_ty = ""
        body = (
            f"let __r = {call}; let __r: &[{r.elem}] = ::core::convert::AsRef::as_ref(&__r);\n"
            f"        if __r.len() != out_len as usize {{\n"
            f"            return Err(format!(\"{sig.name} returned {{}} values, expected {{}}\", __r.len(), out_len));\n"
            f"        }}\n"
            f"        __slice_mut(out_ptr, out_len).copy_from_slice(__r); Ok(())"
        )
        default = "()"
    else:  # str
        ret_ty = " -> *mut u8"
        body = (
            f"let __r = {call}; let __s: &str = ::core::convert::AsRef::as_ref(&__r);\n"
            f"        Ok(__out_str(__s, out_len))"
        )
        default = "::core::ptr::null_mut()"
    pre_s = "\n        ".join(pre)
    doc = f"/// {sig.doc}\n" if sig.doc else ""
    return f"""{doc}#[no_mangle]
pub unsafe extern "C" fn {sig.symbol}({params}){ret_ty} {{
    __guard(|| {{
        {pre_s}
        {body}
    }}, {default})
}}
"""


RUST_PRELUDE = """// Generated by twinwrap. Do not edit; it is rewritten on every build.
#![allow(clippy::missing_safety_doc, unused_unsafe)]
use std::cell::RefCell;

thread_local! {
    static __ERROR: RefCell<Option<String>> = const { RefCell::new(None) };
}

fn __set_error(msg: String) {
    __ERROR.with(|e| *e.borrow_mut() = Some(msg));
}

// wasm32-unknown-unknown aborts on panic, so catch_unwind never returns
// there. The hook records the message first; the JS wrapper reads it with
// twinwrap_take_error after the trap. On native targets it also keeps the
// default hook from printing to stderr.
fn __install_hook() {
    static ONCE: std::sync::Once = std::sync::Once::new();
    ONCE.call_once(|| {
        std::panic::set_hook(Box::new(|info| {
            let msg = if let Some(s) = info.payload().downcast_ref::<&str>() { s.to_string() }
                else if let Some(s) = info.payload().downcast_ref::<String>() { s.clone() }
                else { "panic".to_string() };
            __set_error(msg);
        }));
    });
}

fn __guard<T>(f: impl FnOnce() -> Result<T, String>, default: T) -> T {
    __install_hook();
    match std::panic::catch_unwind(std::panic::AssertUnwindSafe(f)) {
        Ok(Ok(v)) => v,
        Ok(Err(msg)) => { __set_error(msg); default }
        // The hook already stored the message.
        Err(_) => default,
    }
}

unsafe fn __slice<'a, T>(p: *const T, n: i32) -> &'a [T] {
    if n <= 0 || p.is_null() { &[] } else { std::slice::from_raw_parts(p, n as usize) }
}

unsafe fn __slice_mut<'a, T>(p: *mut T, n: i32) -> &'a mut [T] {
    if n <= 0 || p.is_null() { &mut [] } else { std::slice::from_raw_parts_mut(p, n as usize) }
}

unsafe fn __str<'a>(p: *const u8, n: i32) -> Result<&'a str, String> {
    std::str::from_utf8(__slice(p, n)).map_err(|e| format!("invalid UTF-8: {e}"))
}

unsafe fn __out_str(s: &str, out_len: *mut i32) -> *mut u8 {
    let n = s.len();
    let p = twinwrap_alloc(n as i32);
    std::ptr::copy_nonoverlapping(s.as_ptr(), p, n);
    *out_len = n as i32;
    p
}

fn __layout(n: i32) -> std::alloc::Layout {
    std::alloc::Layout::from_size_align((n.max(1)) as usize, 8).expect("layout")
}

#[no_mangle]
pub extern "C" fn twinwrap_abi_version() -> i32 { %ABI% }

#[no_mangle]
pub unsafe extern "C" fn twinwrap_alloc(n: i32) -> *mut u8 {
    std::alloc::alloc(__layout(n))
}

#[no_mangle]
pub unsafe extern "C" fn twinwrap_free(p: *mut u8, n: i32) {
    if !p.is_null() { std::alloc::dealloc(p, __layout(n)) }
}

/// Returns the last error message (and clears it), or null when there is none.
#[no_mangle]
pub unsafe extern "C" fn twinwrap_take_error(out_len: *mut i32) -> *mut u8 {
    match __ERROR.with(|e| e.borrow_mut().take()) {
        Some(msg) => __out_str(&msg, out_len),
        None => { *out_len = 0; std::ptr::null_mut() }
    }
}

"""


def rust_glue(m: Manifest, crate_dir: Path) -> str:
    crate = rust_crate_ident(crate_dir)
    parts = [RUST_PRELUDE.replace("%ABI%", str(ABI_VERSION))]
    for sig in m.functions:
        parts.append(_rust_fn(m, crate, sig))
    return "\n".join(parts)
