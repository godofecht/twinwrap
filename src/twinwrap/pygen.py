"""The Python package: a ctypes loader plus one typed function per export.

It uses no part of the CPython C API, so a single wheel per platform runs
on every Python 3 version from 3.8 on.
"""

from __future__ import annotations

from .manifest import Manifest
from .sig import SCALARS, LengthExpr, Signature

PY_HINT = {k: ("bool" if k == "bool" else "float" if k.startswith("f") else "int") for k in SCALARS}
ARRAY_CODE = {
    "i8": "b", "u8": "B", "i16": "h", "u16": "H", "i32": "i", "u32": "I",
    "i64": "q", "u64": "Q", "f32": "f", "f64": "d",
}
INT_RANGE = {
    "i8": (-(2**7), 2**7 - 1), "u8": (0, 2**8 - 1), "i16": (-(2**15), 2**15 - 1),
    "u16": (0, 2**16 - 1), "i32": (-(2**31), 2**31 - 1), "u32": (0, 2**32 - 1),
    "i64": (-(2**63), 2**63 - 1), "u64": (0, 2**64 - 1),
}

RUNTIME = '''\
# Generated by twinwrap. Do not edit.
"""%DOC%"""

from __future__ import annotations

import array as _array
import ctypes as _c
import os as _os
import sys as _sys
from typing import Sequence as _Seq

__version__ = "%VERSION%"
__all__ = [%ALL%]

_HERE = _os.path.dirname(_os.path.abspath(__file__))


def _load() -> _c.CDLL:
    if _sys.platform == "win32":
        name = "%LIB%.dll"
    elif _sys.platform == "darwin":
        name = "lib%LIB%.dylib"
    else:
        name = "lib%LIB%.so"
    path = _os.path.join(_HERE, "_native", name)
    if not _os.path.exists(path):
        raise ImportError(
            f"%PKG%: no native library for this platform at {path}. "
            "Install a wheel built for this OS and CPU."
        )
    lib = _c.CDLL(path)
    got = lib.twinwrap_abi_version()
    if got != %ABI%:
        raise ImportError(f"%PKG%: native library has ABI {got}, wrapper expects %ABI%")
    return lib


_lib = _load()
_lib.twinwrap_free.argtypes = [_c.c_void_p, _c.c_int32]
_lib.twinwrap_free.restype = None
_HAS_ERRORS = hasattr(_lib, "twinwrap_take_error")
if _HAS_ERRORS:
    _lib.twinwrap_take_error.argtypes = [_c.POINTER(_c.c_int32)]
    _lib.twinwrap_take_error.restype = _c.c_void_p


def _check() -> None:
    if not _HAS_ERRORS:
        return
    n = _c.c_int32(0)
    p = _lib.twinwrap_take_error(_c.byref(n))
    if p:
        msg = _c.string_at(p, n.value).decode("utf-8", "replace")
        _lib.twinwrap_free(p, n.value)
        raise RuntimeError(msg)


def _int(name: str, v, lo: int, hi: int) -> int:
    if isinstance(v, bool) or not isinstance(v, int):
        try:
            import operator
            v = operator.index(v)
        except TypeError:
            raise TypeError(f"{name} must be an int, got {type(v).__name__}") from None
    if not lo <= v <= hi:
        raise OverflowError(f"{name}={v} is outside [{lo}, {hi}]")
    return v


def _len(name: str, n: int) -> int:
    if n < 0 or n > 2**31 - 1:
        raise ValueError(f"{name}: length {n} is outside [0, 2**31 - 1]")
    return n


def _slice(name: str, x, ctype, code: str):
    """(pointer, length, keep-alive) for a sequence or buffer of numbers."""
    try:
        mv = memoryview(x)
    except TypeError:
        mv = None
    if mv is not None and mv.c_contiguous and mv.ndim == 1 and mv.format.lstrip("@=<") in (code, ) \\
            and mv.itemsize == _c.sizeof(ctype) and not mv.readonly:
        n = _len(name, mv.shape[0])
        buf = (ctype * n).from_buffer(mv) if n else (ctype * 0)()
        return _c.cast(buf, _c.POINTER(ctype)), n, (buf, mv)
    seq = list(x)
    n = _len(name, len(seq))
    buf = (ctype * n)(*seq)
    return _c.cast(buf, _c.POINTER(ctype)), n, buf


def _bytes(name: str, s: str):
    if not isinstance(s, str):
        raise TypeError(f"{name} must be a str, got {type(s).__name__}")
    b = s.encode("utf-8")
    n = _len(name, len(b))
    buf = _c.create_string_buffer(b, n or 1)
    return _c.cast(buf, _c.POINTER(_c.c_uint8)), n, buf
'''


def _hint(t) -> str:
    if t.kind == "scalar":
        return PY_HINT[t.elem]
    if t.kind == "slice":
        return f"_Seq[{PY_HINT[t.elem]}]"
    if t.kind == "str":
        return "str"
    if t.kind == "array":
        return "_array.array"
    return "None"


def _fn(sig: Signature) -> str:
    sym = sig.symbol
    argtypes: list[str] = []
    for p in sig.params:
        t = p.type
        if t.kind == "scalar":
            argtypes.append(f"_c.{SCALARS[t.elem][1]}")
        elif t.kind == "slice":
            argtypes += [f"_c.POINTER(_c.{SCALARS[t.elem][1]})", "_c.c_int32"]
        elif t.kind == "str":
            argtypes += ["_c.POINTER(_c.c_uint8)", "_c.c_int32"]
    r = sig.ret
    if r.kind == "array":
        argtypes += [f"_c.POINTER(_c.{SCALARS[r.elem][1]})", "_c.c_int32"]
        restype = "None"
    elif r.kind == "str":
        argtypes.append("_c.POINTER(_c.c_int32)")
        restype = "_c.c_void_p"
    elif r.kind == "scalar":
        restype = f"_c.{SCALARS[r.elem][1]}"
    else:
        restype = "None"

    params = ", ".join(f"{p.name}: {_hint(p.type)}" for p in sig.params)
    lines = [
        f"_lib.{sym}.argtypes = [{', '.join(argtypes)}]",
        f"_lib.{sym}.restype = {restype}",
        "",
        "",
        f"def {sig.name}({params}) -> {_hint(r)}:",
    ]
    doc = sig.doc or str(sig)
    lines.append(f'    """{doc}"""')
    call: list[str] = []
    lens: dict[str, str] = {}
    for p in sig.params:
        t = p.type
        if t.kind == "scalar":
            if t.elem in INT_RANGE:
                lo, hi = INT_RANGE[t.elem]
                lines.append(f"    {p.name} = _int({p.name!r}, {p.name}, {lo}, {hi})")
            elif t.elem == "bool":
                lines.append(f"    {p.name} = bool({p.name})")
            else:
                lines.append(f"    {p.name} = float({p.name})")
            call.append(p.name)
        elif t.kind == "slice":
            ct = f"_c.{SCALARS[t.elem][1]}"
            lines.append(
                f"    _{p.name}_p, _{p.name}_n, _{p.name}_k = "
                f"_slice({p.name!r}, {p.name}, {ct}, {ARRAY_CODE[t.elem]!r})"
            )
            call += [f"_{p.name}_p", f"_{p.name}_n"]
            lens[p.name] = f"_{p.name}_n"
        elif t.kind == "str":
            lines.append(f"    _{p.name}_p, _{p.name}_n, _{p.name}_k = _bytes({p.name!r}, {p.name})")
            call += [f"_{p.name}_p", f"_{p.name}_n"]
            lens[p.name] = f"_{p.name}_n"
    if r.kind == "array":
        expr = LengthExpr(r.length or "", sig).render(
            "py", lambda name, is_len: lens[name] if is_len else name
        )
        ct = f"_c.{SCALARS[r.elem][1]}"
        lines += [
            f"    _n = _len('result', {expr})",
            f"    _out = _array.array({ARRAY_CODE[r.elem]!r}, bytes(_n * _c.sizeof({ct})))",
            f"    _ob = ({ct} * _n).from_buffer(_out) if _n else ({ct} * 0)()",
            f"    _lib.{sym}({', '.join(call + [f'_c.cast(_ob, _c.POINTER({ct}))', '_n'])})",
            "    _check()",
            "    return _out",
        ]
    elif r.kind == "str":
        lines += [
            "    _n = _c.c_int32(0)",
            f"    _p = _lib.{sym}({', '.join(call + ['_c.byref(_n)'])})",
            "    _check()",
            "    if not _p:",
            "        return ''",
            "    try:",
            "        return _c.string_at(_p, _n.value).decode('utf-8')",
            "    finally:",
            "        _lib.twinwrap_free(_p, _n.value)",
        ]
    elif r.kind == "scalar":
        lines += [f"    _r = _lib.{sym}({', '.join(call)})", "    _check()", "    return _r"]
    else:
        lines += [f"    _lib.{sym}({', '.join(call)})", "    _check()"]
    return "\n".join(lines) + "\n"


def python_module(m: Manifest, abi: int) -> str:
    head = (
        RUNTIME.replace("%DOC%", (m.description or m.name).replace('"""', "'''"))
        .replace("%VERSION%", m.version)
        .replace("%ALL%", ", ".join(repr(f.name) for f in m.functions))
        .replace("%LIB%", m.lib_name)
        .replace("%PKG%", m.name)
        .replace("%ABI%", str(abi))
    )
    return head + "\n\n" + "\n\n".join(_fn(s) for s in m.functions)
