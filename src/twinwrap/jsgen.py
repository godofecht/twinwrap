"""The npm package: a loader for the .wasm module, one function per export,
and TypeScript declarations.

Rust builds for wasm32-unknown-unknown and imports nothing. Flow builds for
wasm32-wasip1 as a reactor; library code rarely reaches the C library's
system calls, so the loader supplies a small WASI layer only for the
imports the module actually declares.
"""

from __future__ import annotations

from .manifest import Manifest
from .pygen import INT_RANGE
from .sig import SCALARS, LengthExpr, Signature

TS_TYPE = {k: ("bigint" if k in ("i64", "u64") else "boolean" if k == "bool" else "number") for k in SCALARS}

RUNTIME = r"""// Generated by twinwrap. Do not edit.
'use strict';

const fs = require('fs');
const path = require('path');

const ABI = %ABI%;
const WASM = path.join(__dirname, '%LIB%.wasm');

class WasiExit extends Error {
  constructor(code) { super(`wasm module called proc_exit(${code})`); this.code = code; }
}

// Only the WASI calls the module imports are provided. Anything it imports
// but never calls returns ENOSYS.
function wasiImports(getMemory) {
  const ENOSYS = 52, EBADF = 8;
  const mem = () => new DataView(getMemory().buffer);
  const out = { 1: [], 2: [] };
  const impl = {
    fd_write(fd, iovs, iovsLen, nwritten) {
      const dv = mem();
      let total = 0;
      for (let i = 0; i < iovsLen; i++) {
        const p = dv.getUint32(iovs + i * 8, true), n = dv.getUint32(iovs + i * 8 + 4, true);
        if (fd === 1 || fd === 2) out[fd].push(Buffer.from(getMemory().buffer, p, n).toString());
        total += n;
      }
      dv.setUint32(nwritten, total, true);
      if (fd === 1 || fd === 2) {
        const s = out[fd].join(''); out[fd] = [];
        (fd === 1 ? process.stdout : process.stderr).write(s);
        return 0;
      }
      return EBADF;
    },
    proc_exit(code) { throw new WasiExit(code); },
    environ_sizes_get(c, s) { const dv = mem(); dv.setUint32(c, 0, true); dv.setUint32(s, 0, true); return 0; },
    environ_get() { return 0; },
    args_sizes_get(c, s) { const dv = mem(); dv.setUint32(c, 0, true); dv.setUint32(s, 0, true); return 0; },
    args_get() { return 0; },
    clock_time_get(id, prec, out) {
      mem().setBigUint64(out, process.hrtime.bigint(), true); return 0;
    },
    random_get(p, n) { require('crypto').randomFillSync(new Uint8Array(getMemory().buffer, p, n)); return 0; },
    fd_close() { return 0; },
    fd_fdstat_get() { return EBADF; },
    fd_seek() { return EBADF; },
    fd_prestat_get() { return EBADF; },
  };
  return new Proxy(impl, { get: (t, k) => (k in t ? t[k] : () => ENOSYS) });
}

function load() {
  const module = new WebAssembly.Module(fs.readFileSync(WASM));
  let memory = null;
  const imports = {};
  for (const imp of WebAssembly.Module.imports(module)) {
    if (imp.module === 'wasi_snapshot_preview1') {
      imports[imp.module] = imports[imp.module] || wasiImports(() => memory);
    } else {
      throw new Error(`%PKG%: wasm module imports ${imp.module}.${imp.name}, which twinwrap does not provide`);
    }
  }
  const instance = new WebAssembly.Instance(module, imports);
  const x = instance.exports;
  memory = x.memory;
  if (typeof x._initialize === 'function') x._initialize();
  const got = x.twinwrap_abi_version();
  if (got !== ABI) throw new Error(`%PKG%: wasm module has ABI ${got}, wrapper expects ${ABI}`);
  return x;
}

const w = load();
const enc = new TextEncoder();
const dec = new TextDecoder('utf-8', { fatal: true });
const u8 = () => new Uint8Array(w.memory.buffer);

function check() {
  if (typeof w.twinwrap_take_error !== 'function') return;
  const lp = w.twinwrap_alloc(4);
  try {
    const p = w.twinwrap_take_error(lp);
    if (p) {
      const n = new DataView(w.memory.buffer).getInt32(lp, true);
      const msg = Buffer.from(w.memory.buffer, p, n).toString('utf-8');
      w.twinwrap_free(p, n);
      throw new Error(msg);
    }
  } finally { w.twinwrap_free(lp, 4); }
}

function len(name, n) {
  if (!Number.isInteger(n) || n < 0 || n > 2147483647) throw new RangeError(`${name}: length ${n} is outside [0, 2**31 - 1]`);
  return n;
}

function int(name, v, lo, hi) {
  if (typeof v === 'boolean' || !(typeof v === 'number' ? Number.isInteger(v) : typeof v === 'bigint'))
    throw new TypeError(`${name} must be an integer, got ${typeof v}`);
  if (v < lo || v > hi) throw new RangeError(`${name}=${v} is outside [${lo}, ${hi}]`);
  return v;
}

// A Rust panic in wasm traps. The panic hook saved its message, so report
// that instead of "unreachable". The module may be left inconsistent.
function trap(e) {
  if (e instanceof WebAssembly.RuntimeError && typeof w.twinwrap_take_error === 'function') {
    try { check(); } catch (inner) { inner.cause = e; return inner; }
  }
  return e;
}

const BIG = new Set([BigInt64Array, BigUint64Array]);

// Copies values into wasm memory; returns [pointer, length, byteLength].
function putSlice(name, xs, Typed) {
  let src = xs;
  if (!(xs instanceof Typed)) {
    if (BIG.has(Typed)) {
      src = Typed.from(xs, (v, i) => {
        if (typeof v === 'number') {
          if (!Number.isSafeInteger(v)) throw new RangeError(`${name}[${i}]=${v} is not a safe integer; pass a BigInt`);
          return BigInt(v);
        }
        return v;
      });
    } else {
      src = Typed.from(xs);
    }
  }
  const n = len(name, src.length);
  const bytes = n * Typed.BYTES_PER_ELEMENT;
  const p = w.twinwrap_alloc(bytes);
  new Typed(w.memory.buffer, p, n).set(src);
  return [p, n, bytes];
}

function putStr(name, s) {
  if (typeof s !== 'string') throw new TypeError(`${name} must be a string, got ${typeof s}`);
  const b = enc.encode(s);
  const n = len(name, b.length);
  const p = w.twinwrap_alloc(n);
  u8().set(b, p);
  return [p, n, n];
}
"""


def _ts(t) -> str:
    if t.kind == "scalar":
        return TS_TYPE[t.elem]
    if t.kind == "slice":
        arr = SCALARS[t.elem][4]
        el = TS_TYPE[t.elem]
        return f"{arr} | ArrayLike<{el}>"
    if t.kind == "str":
        return "string"
    if t.kind == "array":
        return SCALARS[t.elem][4]  # type: ignore[return-value]
    return "void"


def _fn(sig: Signature) -> str:
    sym = sig.symbol
    params = ", ".join(p.name for p in sig.params)
    body: list[str] = []
    frees: list[str] = []
    call: list[str] = []
    lens: dict[str, str] = {}
    for p in sig.params:
        t = p.type
        if t.kind == "scalar":
            if t.elem in INT_RANGE:
                lo, hi = INT_RANGE[t.elem]
                if t.elem in ("i64", "u64"):
                    body.append(
                        f"  {p.name} = BigInt(int('{p.name}', typeof {p.name} === 'number' ? BigInt({p.name}) : {p.name}, {lo}n, {hi}n));"
                    )
                else:
                    body.append(f"  int('{p.name}', {p.name}, {lo}, {hi});")
                call.append(p.name)
            elif t.elem == "bool":
                call.append(f"({p.name} ? 1 : 0)")
            else:
                body.append(f"  {p.name} = Number({p.name});")
                call.append(p.name)
        elif t.kind == "slice":
            body.append(f"  const [{p.name}P, {p.name}N, {p.name}B] = putSlice('{p.name}', {p.name}, {SCALARS[t.elem][4]});")
            frees.append(f"w.twinwrap_free({p.name}P, {p.name}B);")
            call += [f"{p.name}P", f"{p.name}N"]
            lens[p.name] = f"{p.name}N"
        elif t.kind == "str":
            body.append(f"  const [{p.name}P, {p.name}N, {p.name}B] = putStr('{p.name}', {p.name});")
            frees.append(f"w.twinwrap_free({p.name}P, {p.name}B);")
            call += [f"{p.name}P", f"{p.name}N"]
            lens[p.name] = f"{p.name}N"
    r = sig.ret
    tail: list[str] = []
    if r.kind == "array":
        typed = SCALARS[r.elem][4]
        expr = LengthExpr(r.length or "", sig).render(
            "js", lambda name, is_len: lens[name] if is_len else f"Number({name})"
        )
        body += [
            f"  const outN = len('result', {expr});",
            f"  const outB = outN * {typed}.BYTES_PER_ELEMENT;",
            "  const outP = w.twinwrap_alloc(outB);",
        ]
        frees.insert(0, "w.twinwrap_free(outP, outB);")
        call += ["outP", "outN"]
        tail = [
            f"    w.{sym}({', '.join(call)});",
            "    check();",
            f"    return new {typed}(w.memory.buffer, outP, outN).slice();",
        ]
    elif r.kind == "str":
        body.append("  const lenP = w.twinwrap_alloc(4);")
        frees.insert(0, "w.twinwrap_free(lenP, 4);")
        call.append("lenP")
        tail = [
            f"    const p = w.{sym}({', '.join(call)});",
            "    check();",
            "    if (!p) return '';",
            "    const n = new DataView(w.memory.buffer).getInt32(lenP, true);",
            "    const s = dec.decode(new Uint8Array(w.memory.buffer, p, n));",
            "    w.twinwrap_free(p, n);",
            "    return s;",
        ]
    elif r.kind == "scalar":
        conv = "!!r" if r.elem == "bool" else "r"
        if r.elem == "u32":
            conv = "r >>> 0"
        elif r.elem == "u64":
            conv = "BigInt.asUintN(64, r)"
        elif r.elem in ("u8", "u16"):
            conv = f"r & {INT_RANGE[r.elem][1]}"
        tail = [f"    const r = w.{sym}({', '.join(call)});", "    check();", f"    return {conv};"]
    else:
        tail = [f"    w.{sym}({', '.join(call)});", "    check();"]
    doc = sig.doc or str(sig)
    lines = [f"/** {doc} */", f"function {sig.name}({params}) {{", *body]
    if frees:
        lines += ["  try {", *tail, "  } catch (e) {", "    throw trap(e);",
                  "  } finally {", *[f"    {f}" for f in frees], "  }"]
    else:
        lines += ["  try {", *tail, "  } catch (e) {", "    throw trap(e);", "  }"]
    lines.append("}")
    return "\n".join(lines) + "\n"


def js_module(m: Manifest, abi: int) -> str:
    head = RUNTIME.replace("%ABI%", str(abi)).replace("%LIB%", m.lib_name).replace("%PKG%", m.name)
    fns = "\n".join(_fn(s) for s in m.functions)
    exports = ", ".join(f.name for f in m.functions)
    return f"{head}\n{fns}\nmodule.exports = {{ {exports} }};\n"


def dts(m: Manifest) -> str:
    lines = [f"// {m.name} {m.version}. Generated by twinwrap.", ""]
    for s in m.functions:
        params = ", ".join(f"{p.name}: {_ts(p.type)}" for p in s.params)
        lines.append(f"/** {s.doc or str(s)} */")
        lines.append(f"export declare function {s.name}({params}): {_ts(s.ret)};")
    return "\n".join(lines) + "\n"
